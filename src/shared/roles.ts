const BY_ID = new Map<RoleId, Role>(ROLES.map(role => [role.id, role]));

export function getRole(id: RoleId): Role {
	const role = BY_ID.get(id);
	if (!role) {
		throw new Error(`Rôle inconnu : ${id}`);
	}
	return role;
}

/** Nom du rôle avec l'article en minuscule, pour l'insérer dans une phrase. */
export function roleLabel(id: RoleId): string {
	return getRole(id).name.replace(/^(Le|La|L')/u, article => article.toLowerCase());
}

export function roleImage(id: RoleId): string {
	return `cards/${id}.webp`;
}
